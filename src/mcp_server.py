"""Read-only MCP server for CORA: a thin wrapper around the CORA REST API.

    python src/run.py serve            # start the API first (default http://127.0.0.1:8000)
    python src/mcp_server.py           # MCP over stdio; set CORA_API_URL to point elsewhere

Tools: search_records, get_record, ask_archive. Nothing can be written or changed through it.
"""
import json
import os
import urllib.parse
import urllib.request

from mcp.server.mcpserver import MCPServer

API = os.environ.get("CORA_API_URL", "http://127.0.0.1:8000").rstrip("/")
mcp = MCPServer("cora-archive")


def _get(path: str, **params) -> dict:
    qs = urllib.parse.urlencode({k: v for k, v in params.items() if v not in (None, "")})
    with urllib.request.urlopen(f"{API}{path}{'?' + qs if qs else ''}", timeout=180) as r:
        return json.load(r)


@mcp.tool()
def search_records(query: str = "", document_type: str = "", source_level: str = "", decade: str = "",
                   page: int = 1) -> dict:
    """Full-text search over the Apertus-classified records of the Swiss Federal Archives.
    Filters: document_type (e.g. 'photograph'), source_level ('primary'|'secondary'|'tertiary'), decade (e.g. '1910s').
    Returns record summaries (id, title, type, date, résumé, reference code) and facet counts."""
    return _get("/api/records", q=query, document_type=document_type, source_level=source_level,
                decade=decade, page=page, size=10)


@mcp.tool()
def get_record(record_id: str) -> dict:
    """Full AI-ready record by ID: untouched original fields, Apertus classification, archival location,
    entities with Wikidata links, preprocessing needs, personal-data flags, story trail, provenance and QC."""
    return _get(f"/api/records/{urllib.parse.quote(record_id)}")


@mcp.tool()
def ask_archive(question: str) -> dict:
    """Answer a question from the records only. Every sentence cites record IDs (with archive portal links);
    if nothing relevant is retrieved the answer says so instead of answering. The answer text is generated by Apertus."""
    return _get("/api/ask", q=question)


if __name__ == "__main__":
    mcp.run()
